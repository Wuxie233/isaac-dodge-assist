--[[
item_emulator.lua - pure-Lua emulation of The Binding of Isaac: Repentance+ item pools
(v1.9.7.17.J460, vanilla, no REPENTOGON). Lua 5.3 integers; no game calls.

Reconstructed from isaac-ng.exe (ItemPool::GetCollectible @0x733610, pick @0x732fa0,
ItemPool::shuffle_pools, Entity_Pickup::Init @0x6e02f0, Room::GetItemPool @0x7ebe20) and
validated offline on 130 logged pedestals (see native/research/item-emulation.md).

  local Emu  = require("item_emulator")        -- or dofile
  local data = require("item_pool_data")       -- generated by gen_data.py
  local emu  = Emu.new(data, startSeed)        -- Game():GetSeeds():GetStartSeed()

  -- keep the run history in sync (all calls are local bookkeeping):
  emu:recordPick(poolType, item)   -- a collectible was chosen from poolType with decrease
                                   -- (pedestal spawned from a pool: weight -= DecreaseBy ...)
  emu:removeCollectible(item)      -- item left the pools (player got it: AddCollectible)
  emu:newRoom()                    -- room changed: clears the room blacklist

  -- predict (pure; no state change):
  local id = emu:predict(poolType, seed, { isAvailable = fn(id)->bool, banActives = bool })

  Seeds:
    pedestal placed by a room layout, spawn i (0-based index in Data.Spawns):
      Emu.layoutPickSeed(desc.SpawnSeed, i)       -- = X35(InitSeed), InitSeed = X35(X11^(i+1)(SpawnSeed))
    boss clear reward (first pedestal):  Emu.bossPickSeed(desc.AwardSeed)  -- = X35(AwardSeed)
      pool: Emu.bossRewardPool(desc.Data.Subtype)  (nil = Horsemen fixed drop)
    co-op boss room, the next item (one per extra player, spawned once the first is taken):
      Emu.extraBossPickSeed(firstInitSeed)  -- = X30(InitSeed of the first boss pedestal), boss pool
      firstInitSeed = Emu.bossItemInitSeed(desc.AwardSeed, desc.Data.Subtype)  -- X35^3, Mom X35^2
  Pools: Emu.poolForRoom(roomType, { subtype=, devilTreasure=, greed= })
]]

local M = {}

local M32 = 0xFFFFFFFF

-- Marsaglia xorshift triplets used by the game's RNG (index = RNG shift index)
local SHIFT = {
  [3]  = {1, 9, 29},   -- item pool init RNG
  [4]  = {1, 11, 6},   -- GetCollectible pick RNG
  [11] = {2, 7, 7},    -- room layout spawn RNG
  [12] = {2, 7, 9},    -- room seed derivation (AwardSeed = X12(SpawnSeed))
  [27] = {3, 23, 25},  -- start seed RNG (stage seeds ...)
  [30] = {4, 3, 17},   -- co-op extra boss item, from the first boss pedestal's InitSeed
  [35] = {5, 9, 7},    -- default RNG (entity InitSeed RNG)
}

local function xs(x, s)
  x = x ~ (x >> s[1])
  x = x ~ ((x << s[2]) & M32)
  x = x ~ (x >> s[3])
  return x & M32
end

--- One RNG:Next() with shift index idx (3, 4, 11, 12, 27 or 35).
function M.next(seed, idx)
  return xs(seed & M32, SHIFT[idx])
end
local X = M.next

--- Seed string ("ABCD EFGH") -> start seed integer (Seeds.String2Seed).
function M.seedFromString(str)
  local table_ = "ABCDEFGHJKLMNPQRSTWXYZ01234V6789"
  str = str:gsub(" ", "")
  local v = 0
  for i = 1, 8 do
    local c = str:sub(i, i)
    local p = table_:find(c, 1, true)
    if not p then return nil end
    v = v | ((p - 1) << (5 * (8 - i)))
  end
  return ((v >> 8) ~ 0xFEF7FFD) & M32
end

-- float32 rounding (the game keeps weights, totals and pick targets in float32)
local f32
if string.pack then
  local pack, unpack = string.pack, string.unpack
  f32 = function(x) return (unpack("<f", pack("<f", x))) end
else
  f32 = function(x) return x + 0.0 end   -- fallback: double (rare boundary differences)
end
M.f32 = f32

local C_UNIT = f32(2.3283061589829401e-10)   -- float at 0xba9ff0
local REPICK_DIV = f32(3.3731698989868164)     -- float at 0xbaa714

-- MT19937 (std::mt19937) used once per run to shuffle the pools
local function mt19937(seed)
  local mt = {}
  mt[0] = seed & M32
  for i = 1, 623 do
    local p = mt[i - 1]
    mt[i] = (1812433253 * (p ~ (p >> 30)) + i) & M32
  end
  local idx = 624
  return function()
    if idx >= 624 then
      for i = 0, 623 do
        local y = (mt[i] & 0x80000000) | (mt[(i + 1) % 624] & 0x7FFFFFFF)
        local v = mt[(i + 397) % 624] ~ (y >> 1)
        if y & 1 == 1 then v = v ~ 0x9908B0DF end
        mt[i] = v
      end
      idx = 0
    end
    local y = mt[idx]
    idx = idx + 1
    y = y ~ (y >> 11)
    y = y ~ ((y << 7) & 0x9D2C5680)
    y = y ~ ((y << 15) & 0xEFC60000)
    y = y ~ (y >> 18)
    return y & M32
  end
end

--- MT seed of ItemPool::shuffle_pools for a start seed: 17 shift-27 steps (14 stage seeds,
--- player init seed, 2 more) give the item pool RNG seed; 1 + 2*31 shift-3 steps follow.
function M.poolShuffleSeed(startSeed)
  local s = startSeed & M32
  for _ = 1, 17 do s = X(s, 27) end
  for _ = 1, 63 do s = X(s, 3) end
  return s
end

-- ItemPoolType order of data.pools (index = pool type + 1)
M.POOL = {
  TREASURE = 0, SHOP = 1, BOSS = 2, DEVIL = 3, ANGEL = 4, SECRET = 5, LIBRARY = 6, SHELL_GAME = 7,
  GOLDEN_CHEST = 8, RED_CHEST = 9, BEGGAR = 10, DEMON_BEGGAR = 11, CURSE = 12, KEY_MASTER = 13,
  BATTERY_BUM = 14, MOMS_CHEST = 15, GREED_TREASURE = 16, GREED_BOSS = 17, GREED_SHOP = 18,
  GREED_DEVIL = 19, GREED_ANGEL = 20, GREED_CURSE = 21, GREED_SECRET = 22, CRANE_GAME = 23,
  ULTRA_SECRET = 24, BOMB_BUM = 25, PLANETARIUM = 26, OLD_CHEST = 27, BABY_SHOP = 28,
  WOODEN_CHEST = 29, ROTTEN_BEGGAR = 30,
}

-- Room type -> pool (ItemPool table at +0x69c; -1 falls back to treasure in GetSeededCollectible)
local ROOM_POOL = {
  [1] = -1, [2] = 1, [4] = 0, [5] = 2, [7] = 5, [8] = 5, [10] = 12, [11] = 0, [12] = 6, [14] = 3,
  [15] = 4, [16] = 0, [17] = 0, [18] = 0, [19] = 0, [20] = 8, [21] = 0, [22] = 1, [24] = 26, [29] = 24,
}

--- Pool used for a pedestal that a room layout places (Room::GetItemPool, normal mode).
--- opts.devilTreasure: treasure room with RoomDescriptor.FLAG_DEVIL_TREASURE (Devil's Crown)
--- opts.subtype: Data.Subtype (challenge room subtype 1 = boss challenge)
--- Returns nil for cases this module does not model (greed mode, I AM ERROR room).
function M.poolForRoom(roomType, opts)
  opts = opts or {}
  if opts.greed or roomType == 3 then return nil end
  local t = roomType
  if t == 4 and opts.devilTreasure then t = 14 end
  if t == 11 and opts.subtype == 1 then t = 5 end
  local p = ROOM_POOL[t]
  if p == nil or p < 0 then p = 0 end
  return p
end

--- InitSeed of the entity placed by spawn index i (0-based) of an unvisited room's layout.
function M.layoutInitSeed(spawnSeed, i)
  local s = spawnSeed & M32
  for _ = 1, i + 1 do s = X(s, 11) end
  return X(s, 35)
end

--- Seed that Entity_Pickup::Init passes to GetCollectible for a 5.100.0 / 5.150.x entity.
function M.pickSeedFromInitSeed(initSeed) return X(initSeed & M32, 35) end

function M.layoutPickSeed(spawnSeed, i) return X(M.layoutInitSeed(spawnSeed, i), 35) end

--- Seed of the first boss-room clear reward (AwardSeed = X12(SpawnSeed)).
function M.bossPickSeed(awardSeed) return X(awardSeed & M32, 35) end

--- InitSeed of that first reward pedestal: X35^3(AwardSeed), in Mom's room (boss 6) X35^2
--- (2026-11-05 Online log: six boss rooms and one Mom room).
local MOM = 6
function M.bossItemInitSeed(awardSeed, bossSubtype)
  local s = awardSeed & M32
  for _ = 1, bossSubtype == MOM and 2 or 3 do s = X(s, 35) end
  return s
end

--- With more than one player a boss room drops one more item per extra player, from the boss
--- pool, each spawned once the previous one is taken. The first of them picks with
--- X30(InitSeed of the first boss pedestal) (seven of seven logged rooms); later ones are not
--- modelled.
function M.extraBossPickSeed(firstInitSeed) return X(firstInitSeed & M32, 30) end

--- Pool of the first boss reward from the boss room's Data.Subtype (= boss id).
--- The Fallen (23) rewards from the devil pool [C-log]; the Horsemen (Famine 9, Pestilence 10,
--- War 11, Death 12, Headless Horseman 22, Conquest 38) drop fixed items (nil: not a pool pick).
--- Other bosses: boss pool (thematic pools from the boss config field +0x30 are not modelled).
local HORSEMEN = { [9] = true, [10] = true, [11] = true, [12] = true, [22] = true, [38] = true }
function M.bossRewardPool(bossSubtype)
  if HORSEMEN[bossSubtype] then return nil end
  if bossSubtype == 23 then return 3 end
  return 2
end

