local Emu = {}
Emu.__index = Emu

--- data: table from item_pool_data.lua; startSeed: integer start seed.
function M.new(data, startSeed)
  local self = setmetatable({ pools = {}, removed = {}, roomBlacklist = {}, data = data }, Emu)
  local mt = mt19937(M.poolShuffleSeed(startSeed))
  for p = 1, #data.pools do
    local src = data.pools[p].items
    local n = #src
    -- the game's _totalWeight: float32 sum in XML order
    local total = 0.0
    for i = 1, n do total = f32(total + f32(src[i][2])) end
    -- shuffle (0-based Fisher-Yates from the end, j = mt() % (i+1))
    local order = {}
    for i = 1, n do order[i] = i end
    for i = n - 1, 1, -1 do
      local j = mt() % (i + 1)
      order[i + 1], order[j + 1] = order[j + 1], order[i + 1]
    end
    local pool = { id = {}, w0 = {}, dec = {}, rem = {}, w = {}, prefix = {}, n = n, total = total, index = {} }
    local acc = 0.0
    for k = 1, n do
      local e = src[order[k]]
      local w0 = f32(e[2])
      pool.id[k] = e[1]
      pool.w0[k] = w0
      pool.dec[k] = f32(e[3])
      pool.rem[k] = f32(e[4])
      pool.w[k] = w0
      acc = f32(acc + w0)
      pool.prefix[k] = acc
      pool.index[e[1]] = k
    end
    self.pools[p] = pool
  end
  return self
end

function Emu:newRoom() self.roomBlacklist = {} end
function Emu:removeCollectible(item) self.removed[item] = true end
function Emu:isRemoved(item) return self.removed[item] == true end

--- Apply what a decreasing pick of `item` from pool type `poolType` did (observed spawn).
function Emu:recordPick(poolType, item)
  local pool = self.pools[poolType + 1]
  local k = pool and pool.index[item]
  if k then
    if pool.w[k] > 0 then
      local w = f32(pool.w[k] - pool.dec[k])
      if w < pool.rem[k] then
        pool.w[k] = 0.0
        self.removed[item] = true
      else
        pool.w[k] = w
      end
    end
  else
    self.removed[item] = true
  end
  self.roomBlacklist[item] = true
end

-- first k with prefix[k] > target (the game's linear walk, done as a binary search)
local function landing(pool, target)
  local lo, hi = 1, pool.n
  if pool.prefix[hi] <= target then return nil end
  while lo < hi do
    local mid = (lo + hi) // 2
    if pool.prefix[mid] > target then hi = mid else lo = mid + 1 end
  end
  return lo
end

-- pick_collectible @0x732fa0 (without the decrease side effects; see Emu:predict)
local function pick(self, pool, target, usable, repicks)
  local tot = pool.total
  while true do
    local k = landing(pool, target)
    if not k then return nil end
    local w0 = pool.w0[k]
    local frac = f32(f32(pool.prefix[k] - target) / w0)
    if f32(1.0 - frac) < f32(pool.w[k] / w0) and usable(pool.id[k]) then
      return pool.id[k]
    end
    if repicks < 1 then
      -- "item pool ran out of repicks": first usable entry after k (wrapping)
      local j = k % pool.n + 1
      while j ~= k do
        if pool.w[j] > 0 and usable(pool.id[j]) then return pool.id[j] end
        j = j % pool.n + 1
      end
      return nil
    end
    target = f32(tot * frac)
    if target == tot then target = f32(tot / REPICK_DIV) end
    repicks = repicks - 1
  end
end

--- Predict GetCollectible(poolType, seed) without changing any state.
--- opts.isAvailable(id): ItemConfig:GetCollectible(id):IsAvailable() in game (achievement,
---   Keeper/Lost tags, T.Lost / Sacred Orb filters, challenge/greed tags). Default: all available.
--- opts.isUnlocked(id): the pool's load-time unlock flag (outer retry loop). Default: all true.
--- opts.banActives: a player holds NO! (flags |= 2: actives banned, 20 repicks).
--- Returns the item id, or nil when the pool is exhausted (the game then falls back to the
--- treasure pool / Breakfast).
function Emu:predict(poolType, seed, opts)
  opts = opts or {}
  local pool = self.pools[poolType + 1]
  if not pool or seed == 0 then return nil end
  local avail, unlocked = opts.isAvailable, opts.isUnlocked
  local removed, bl, data = self.removed, self.roomBlacklist, self.data
  local banActives = opts.banActives
  local function usable(id)
    if removed[id] or bl[id] then return false end
    if banActives then
      local it = data.items[id]
      if it and it.t == 3 then return false end
    end
    if avail and not avail(id) then return false end
    return true
  end
  local repicks = banActives and 20 or 10
  local s = seed & M32
  local function target()
    s = X(s, 4)
    return f32(f32(f32(s + 0.0) * C_UNIT) * pool.total)
  end
  local item = pick(self, pool, target(), usable, repicks)
  local counter = 20
  while item and unlocked and not unlocked(item) and counter > 0 do
    counter = counter - 1
    item = pick(self, pool, target(), usable, repicks)
  end
  return item
end

--- Deep copy of the run state (pools' live weights, removed set, room blacklist).
function Emu:clone()
  local c = setmetatable({ pools = {}, removed = {}, roomBlacklist = {}, data = self.data }, Emu)
  for p, pool in ipairs(self.pools) do
    local w = {}
    for k = 1, pool.n do w[k] = pool.w[k] end
    c.pools[p] = setmetatable({ w = w }, { __index = pool })   -- static arrays shared
  end
  for k, v in pairs(self.removed) do c.removed[k] = v end
  for k, v in pairs(self.roomBlacklist) do c.roomBlacklist[k] = v end
  return c
end

--- Predict the pedestals of one not-yet-visited room, in spawn order. Each pick is applied to a
--- private copy (decrease + room blacklist) before the next, as the game does on room load.
--- picks = { {poolType, seed}, ... }; the room blacklist starts empty (new room).
--- Returns { item1, item2, ... } (nil entries when a pool is exhausted).
function Emu:predictRoom(picks, opts)
  local sim = self:clone()
  sim.roomBlacklist = {}
  local out = {}
  for i, p in ipairs(picks) do
    local item = sim:predict(p[1], p[2], opts)
    out[i] = item
    if item then sim:recordPick(p[1], item) end
  end
  return out
end

--- Convenience: availability predicate from an "achievement unlocked" test (offline use).
function M.achievementAvailability(data, isAchievementUnlocked, extraUnavailable)
  return function(id)
    if extraUnavailable and extraUnavailable[id] then return false end
    local it = data.items[id]
    if not it then return false end
    if it.a and it.a > 0 and not isAchievementUnlocked(it.a) then return false end
    return true
  end
end

M.Emu = Emu
return M
