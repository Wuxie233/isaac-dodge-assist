#!/usr/bin/env python3
"""Generate mod/isaac_dodge_assist/pill_effects.lua from the game's pocketitems.xml and stringtable.sta.

    python3 tools/gen_pill_effects.py <dir with pocketitems.xml and stringtable.sta> mod/isaac_dodge_assist/pill_effects.lua

Rerun after every game update. Both files come from the game's afterbirthp.a (extract copies in
%TEMP% with the game's ResourceExtractor, never in the game folder); see native/research/text-and-fonts.md
and native/research/stats-and-pills.md.

pocketitems.xml has one <pilleffect id=... name="#KEY" class="..."/> per PillEffect (0..49). Its
comment defines class as a digit (3 major, 2 medium, 1 minor, 0 joke) plus "+" (positive), "-"
(negative) or nothing (neutral). The game stores the digit as EffectClass and the sign as
EffectSubClass (1 "+", 2 "-", 0 none) and uses the digit only when it deals colours at run start.
Horse pills (PillColor | 0x800) use the same effect id, name and class; there are no separate
horse entries or strings. Names come from the string table's English and "Chinese (Simple)" columns,
as in gen_item_names.py.
"""
import os
import sys
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_item_names import EN, ZH, VERSION, load_stringtable, lookup, lua_str  # noqa: E402

SIGN = {'+': 'good', '-': 'bad', '': 'neutral'}


def main(src, out):
    cats, langs = load_stringtable(src + '/stringtable.sta')
    root = ET.parse(src + '/pocketitems.xml').getroot()
    rows = []
    for e in root.iter('pilleffect'):
        a = e.attrib
        cls = a['class']
        tier, sign = int(cls[0]), cls[1:]
        assert sign in SIGN, cls
        strings = lookup(cats, a['name'])
        en = strings[langs[EN]] if strings else a['name']
        zh = strings[langs[ZH]] if strings and strings[langs[ZH]].strip() else None
        rows.append((int(a['id']), en, zh, SIGN[sign], tier, int(a.get('achievement', -1)),
                     a.get('greedmode') == 'false'))
    rows.sort()
    assert [r[0] for r in rows] == list(range(len(rows))), 'pill effect ids are not 0..n-1'

    o = ['-- Generated by tools/gen_pill_effects.py from the installed game\'s pocketitems.xml/stringtable.sta',
         '-- (Repentance+ v%s, resources extracted from afterbirthp.a). Do not edit by hand.' % VERSION,
         '-- [PillEffect id] = { en, zh ("Chinese (Simple)", Options.Language "zh"), class = good|bad|neutral',
         '--   (pocketitems.xml class sign), tier = class digit (3 major, 2 medium, 1 minor, 0 joke),',
         '--   ach = unlocking achievement (absent: always available), nogreed = not in Greed mode }.',
         '-- Horse pills (PillColor | 0x800) share the id, name and class of their effect.',
         'return {']
    for i, en, zh, cls, tier, ach, nogreed in rows:
        parts = ['en = %s' % lua_str(en)]
        if zh:
            parts.append('zh = %s' % lua_str(zh))
        parts += ['class = "%s"' % cls, 'tier = %d' % tier]
        if ach >= 0:
            parts.append('ach = %d' % ach)
        if nogreed:
            parts.append('nogreed = true')
        o.append('  [%d] = { %s },' % (i, ', '.join(parts)))
    o.append('}')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')
    counts = {c: sum(1 for r in rows if r[3] == c) for c in ('good', 'bad', 'neutral')}
    print('pill effects: %d (ids 0..%d), zh %d, %s' % (len(rows), len(rows) - 1, sum(1 for r in rows if r[2]), counts))
    print('->', out)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
