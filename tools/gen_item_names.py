#!/usr/bin/env python3
"""Generate mod/isaac_dodge_assist/item_names.lua from the game's items.xml and stringtable.sta.

    python3 tools/gen_item_names.py <dir with items.xml and stringtable.sta> mod/isaac_dodge_assist/item_names.lua

Rerun after every game update. Both files come from the game's afterbirthp.a
(the Rep+ archive): copy the archive, the game's tools/ResourceExtractor and its
filelist.txt to %TEMP% and extract there with relative paths (absolute paths
crash it); never write into the game folder. The extractor appends NUL padding
to stringtable.sta, which is stripped here. See native/research/text-and-fonts.md.

items.xml names collectibles and trinkets by localisation key ("#THE_SAD_ONION_NAME").
The key is looked up in the string table's "Items" category (then any other
category). en is the "English" column (language id 0), zh the "Chinese (Simple)"
column (language id 13, which Options.Language reports as "zh"). A name without
"#" is used as is for en. An id whose Chinese string is empty is left out of zh,
so callers fall back to en. The CN Patch for Rep+ workshop mod ships its own
stringtable.sta in repentance_zh.a; its "Items" category is identical to the
official one, so the official table is the source here.
"""
import sys
import xml.etree.ElementTree as ET

VERSION = '1.9.7.17.J460'
COLLECTIBLE_TAGS = ('passive', 'active', 'familiar')
EN, ZH = '0', '13'  # stringtable <language id>


def load_stringtable(path):
    """Returns ({category: {key: [strings]}}, {language id: string position})."""
    root = ET.fromstring(open(path, 'rb').read().rstrip(b'\0'))
    langs = {}
    for lang in root.find('languages'):
        langs[lang.get('id')] = int(lang.get('index')) - 1  # index 0 is the key itself
    assert langs.get('21') == -1 and EN in langs and ZH in langs, langs
    cats = {}
    for cat in root.findall('category'):
        cats[cat.get('name')] = {k.get('name'): [s.text or '' for s in k.findall('string')] for k in cat.findall('key')}
    return cats, langs


def lookup(cats, name):
    """Strings of a "#KEY" name, None for a literal name; an unknown key raises KeyError."""
    if not name.startswith('#'):
        return None
    key = name[1:]
    for cat in ['Items'] + [c for c in cats if c != 'Items']:
        if key in cats[cat]:
            return cats[cat][key]
    raise KeyError(name)


def lua_str(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 32:
            out.append('\\%03d' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def names(items, cats, langs, tags):
    en, zh = {}, {}
    for e in items:
        if e.tag not in tags:
            continue
        i, name = int(e.get('id')), e.get('name')
        strings = lookup(cats, name)
        en[i] = strings[langs[EN]] if strings else name
        if strings and strings[langs[ZH]].strip():
            zh[i] = strings[langs[ZH]]
    return en, zh


def main(src, out):
    cats, langs = load_stringtable(src + '/stringtable.sta')
    items = ET.parse(src + '/items.xml').getroot()
    en, zh = names(items, cats, langs, COLLECTIBLE_TAGS)
    ten, tzh = names(items, cats, langs, ('trinket',))

    o = ['-- Generated by tools/gen_item_names.py from the installed game\'s items.xml/stringtable.sta',
         '-- (Repentance+ v%s, resources extracted from afterbirthp.a). Do not edit by hand.' % VERSION,
         '-- en/zh[collectibleId], trinkets_en/trinkets_zh[trinketId]: official names; zh is the string table\'s',
         '-- "Chinese (Simple)" column (Options.Language "zh"). Ids without a Chinese string are absent from zh.',
         'return {', '  version = "%s",' % VERSION]
    for field, table in (('en', en), ('zh', zh), ('trinkets_en', ten), ('trinkets_zh', tzh)):
        o.append('  %s = {' % field)
        o.extend('    [%d] = %s,' % (i, lua_str(table[i])) for i in sorted(table))
        o.append('  },')
    o.append('}')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(o) + '\n')
    for label, a, b in (('collectibles', en, zh), ('trinkets', ten, tzh)):
        missing = sorted(set(a) - set(b))
        print('%s: %d en, %d zh, missing zh %s' % (label, len(a), len(b), missing or 'none'))
    print('->', out)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
