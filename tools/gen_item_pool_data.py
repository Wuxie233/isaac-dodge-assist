#!/usr/bin/env python3
"""Generate mod/isaac_dodge_assist/item_pool_data.lua from the game's itempools.xml / items.xml / items_metadata.xml.

    python3 tools/gen_item_pool_data.py <dir with the three XMLs> mod/isaac_dodge_assist/item_pool_data.lua

Rerun after every game update. The XMLs come from the game's afterbirthp.a
(the Rep+ archive; repentance.a still holds Rep 1.7.9b data): copy the
archive, the game's tools/ResourceExtractor and its filelist.txt to %TEMP%
and extract there with relative paths (absolute paths crash it); never write
into the game folder. Then check the replay: native/tests/item_emulator_regression.lua.
See native/research/item-emulation.md.

Pools are emitted in ItemPoolType order (0..30); items keep their XML order, which is the
order the game shuffles. Weights are kept as the XML decimal strings so Lua parses the same
doubles that the game's strtod sees before it stores them as float32.
"""
import re
import sys

POOL_NAMES = ["treasure", "shop", "boss", "devil", "angel", "secret", "library", "shellGame", "goldenChest",
              "redChest", "beggar", "demonBeggar", "curse", "keyMaster", "batteryBum", "momsChest",
              "greedTreasure", "greedBoss", "greedShop", "greedDevil", "greedAngel", "greedCurse", "greedSecret",
              "craneGame", "ultraSecret", "bombBum", "planetarium", "oldChest", "babyShop", "woodenChest",
              "rottenBeggar"]


def main(src, out):
    pools, cur = {}, None
    for line in open(src + '/itempools.xml', encoding='utf-8-sig'):
        m = re.search(r'<Pool Name="([^"]+)"', line)
        if m:
            cur = pools.setdefault(m.group(1), [])
            continue
        m = re.search(r'<Item Id="(\d+)" Weight="([\d.]+)" DecreaseBy="([\d.]+)" RemoveOn="([\d.]+)"', line)
        if m and '<!--' not in line.split('<Item')[0]:
            cur.append((int(m.group(1)), m.group(2), m.group(3), m.group(4)))
    assert sorted(pools) == sorted(POOL_NAMES), sorted(pools)

    items = {}
    text = open(src + '/items.xml', encoding='utf-8-sig').read()
    for m in re.finditer(r'<(passive|active|familiar)\b([^>]*)/?>', text):
        a = dict(re.findall(r'(\w+)="([^"]*)"', m.group(2)))
        items[int(a['id'])] = {'type': {'passive': 1, 'active': 3, 'familiar': 4}[m.group(1)],
                               'ach': int(a.get('achievement') or -1), 'hidden': a.get('hidden') == 'true'}
    meta = open(src + '/items_metadata.xml', encoding='utf-8-sig').read()
    for m in re.finditer(r'<item\b([^>]*)/?>', meta):
        a = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
        i = int(a['id'])
        if i in items:
            items[i]['q'] = int(a.get('quality', 0))
            items[i]['tags'] = a.get('tags', '').split()

    o = ['-- Generated by tools/gen_item_pool_data.py from the installed game\'s itempools.xml/items.xml/items_metadata.xml',
         '-- (Repentance+ v1.9.7.17.J460, resources extracted from afterbirthp.a). Do not edit by hand.',
         '-- pools[poolType+1] = { name=..., items={ {id, weight, decreaseBy, removeOn}, ... } } in XML order.',
         '-- items[id] = { t=type(1 passive,3 active,4 familiar), a=achievementId(-1 none), q=quality, nokeeper=bool }',
         'return {', '  version = "1.9.7.17.J460",', '  pools = {']
    for idx, name in enumerate(POOL_NAMES):
        ents = ','.join('{%d,%s,%s,%s}' % e for e in pools[name])
        o.append('    { name = "%s", items = {%s} }, -- %d' % (name, ents, idx))
    o.append('  },')
    o.append('  items = {')
    for i in sorted(items):
        it = items[i]
        extra = ', nokeeper=true' if 'nokeeper' in it.get('tags', []) else ''
        o.append('    [%d] = { t=%d, a=%d, q=%d%s },' % (i, it['type'], it['ach'], it.get('q', 0), extra))
    o.append('  },')
    o.append('}')
    open(out, 'w').write('\n'.join(o) + '\n')
    print('pools', len(POOL_NAMES), 'items', len(items), '->', out)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
